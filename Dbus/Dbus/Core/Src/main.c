void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    // 检查是哪个UART（因为可能有多个UART在用DMA）
    if (huart->Instance == USART3)
    {
        Rx_data.ch0=(buf[0]|(buf[1]<<8))&0x7ff;
        Rx_data.ch0-=1024;
        Rx_data.ch1=((buf[1]>>3)|(buf[2]<<5))&0x7ff;
        Rx_data.ch1-=1024;
        Rx_data.ch2=((buf[2]>>6)|(buf[3]<<2)|(buf[4]<<10))&0x7ff;
        Rx_data.ch2-=1024;
        Rx_data.ch3=((buf[4]>>1)|(buf[5]<<7))&0x7ff;
        Rx_data.ch3-=1024;
        Rx_data.roll = (buf[16] | (buf[17] << 8)) & 0x07FF;  //左上角滚轮
        Rx_data.roll-= 1024;
 
  Rx_data.SW0 = ((buf[5] >> 4) & 0x000C) >> 2;
  Rx_data.SW1 = (buf[5] >> 4) & 0x0003;//sw1和sw2的值分别由相应的位计算得出
        // 重要：普通模式需要重新启动接收
        HAL_UART_Receive_DMA(huart, buf, 18);
    }
}
