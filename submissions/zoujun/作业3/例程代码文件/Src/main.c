/* USER CODE BEGIN 4 */
void update_rc_debug_data(void)
{
    static uint32_t last_update = 0;
    uint32_t now = HAL_GetTick();
    
    // 每10ms更新一次（100Hz）
    if (now - last_update >= 10)
    {
        last_update = now;
        
        // 获取遥控器数据指针
        const RC_ctrl_t *rc_data = get_remote_control_point();
        if (rc_data == NULL) return;
        
        // 更新通道数据
        rc_debug_ch[0] = rc_data->rc.ch[0];
        rc_debug_ch[1] = rc_data->rc.ch[1];
        rc_debug_ch[2] = rc_data->rc.ch[2];
        rc_debug_ch[3] = rc_data->rc.ch[3];
        rc_debug_ch[4] = rc_data->rc.ch[4];
        
        // 更新开关状态
        rc_debug_sw[0] = rc_data->rc.s[0];
        rc_debug_sw[1] = rc_data->rc.s[1];
        
        // 更新鼠标数据
        rc_debug_mouse[0] = rc_data->mouse.x;
        rc_debug_mouse[1] = rc_data->mouse.y;
        rc_debug_mouse[2] = rc_data->mouse.z;
        rc_debug_mouse_btn = (rc_data->mouse.press_r << 1) | rc_data->mouse.press_l;
        
        // 更新键盘状态
        rc_debug_key = rc_data->key.v;
    }
}
